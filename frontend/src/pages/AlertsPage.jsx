import React, { useState, useEffect } from 'react';
import {
  Bell,
  CheckCircle,
  Clock,
  ShieldAlert,
  ChevronLeft,
  ChevronRight,
  Filter,
  Check
} from 'lucide-react';
import { alertsApi } from '../services/api';
import { SeverityBadge, StatusBadge } from '../components/common/StatusBadge';
import { LoadingSpinner } from '../components/common/LoadingSpinner';
import { ErrorBanner } from '../components/common/ErrorBanner';

export const AlertsPage = () => {
  const [alerts, setAlerts] = useState([]);
  const [pagination, setPagination] = useState({ page: 1, limit: 20, total: 0, totalPages: 1 });
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  const [severityFilter, setSeverityFilter] = useState('');
  const [statusFilter, setStatusFilter] = useState('');
  const [page, setPage] = useState(1);

  const fetchAlerts = async () => {
    setLoading(true);
    setError(null);
    try {
      const params = { page, limit: 20 };
      if (severityFilter) params.severity = severityFilter;
      if (statusFilter) params.status = statusFilter;

      const res = await alertsApi.getAlerts(params);
      if (res.data?.success) {
        setAlerts(res.data.data.alerts || []);
        if (res.data.data.pagination) {
          setPagination(res.data.data.pagination);
        }
      }
    } catch (err) {
      setError(err.response?.data?.error || 'Failed to load alerts');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchAlerts();
  }, [page, severityFilter, statusFilter]);

  const handleUpdateStatus = async (alertId, newStatus) => {
    try {
      await alertsApi.updateStatus(alertId, newStatus);
      fetchAlerts();
    } catch (err) {
      setError(err.response?.data?.error || 'Failed to update alert status');
    }
  };

  return (
    <div data-testid="alerts-page" className="p-8 ml-64 space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h2 data-testid="alerts-title" className="text-xl font-bold text-gray-900 dark:text-white">
            Security Incident Alerts
          </h2>
          <p className="text-xs text-gray-500 dark:text-gray-400 mt-1">
            Prioritized security alerts generated by Isolation Forest anomaly detection
          </p>
        </div>
      </div>

      <ErrorBanner message={error} onDismiss={() => setError(null)} />

      {/* Filter Controls */}
      <div className="bg-white dark:bg-slate-800 p-4 rounded-xl border border-gray-200 dark:border-slate-700 shadow-sm flex flex-wrap gap-4 items-center">
        <div className="flex items-center space-x-2">
          <Filter className="w-4 h-4 text-gray-400" />
          <span className="text-xs font-bold text-gray-700 dark:text-gray-300">Filter By:</span>
        </div>

        {/* Severity Selector */}
        <div className="flex items-center space-x-2">
          <label className="text-xs text-gray-500">Severity:</label>
          <select
            data-testid="filter-alert-severity-select"
            value={severityFilter}
            onChange={(e) => {
              setSeverityFilter(e.target.value);
              setPage(1);
            }}
            className="px-3 py-1.5 rounded-lg border border-gray-300 dark:border-slate-600 bg-white dark:bg-slate-700 text-xs font-medium"
          >
            <option value="">All Severities</option>
            <option value="critical">Critical</option>
            <option value="high">High</option>
            <option value="medium">Medium</option>
            <option value="low">Low</option>
          </select>
        </div>

        {/* Status Selector */}
        <div className="flex items-center space-x-2">
          <label className="text-xs text-gray-500">Status:</label>
          <select
            data-testid="filter-alert-status-select"
            value={statusFilter}
            onChange={(e) => {
              setStatusFilter(e.target.value);
              setPage(1);
            }}
            className="px-3 py-1.5 rounded-lg border border-gray-300 dark:border-slate-600 bg-white dark:bg-slate-700 text-xs font-medium"
          >
            <option value="">All Statuses</option>
            <option value="open">Open</option>
            <option value="acknowledged">Acknowledged</option>
            <option value="resolved">Resolved</option>
          </select>
        </div>
      </div>

      {/* Alert Feed */}
      {loading ? (
        <LoadingSpinner message="Fetching prioritized alerts..." />
      ) : alerts.length === 0 ? (
        <div className="bg-white dark:bg-slate-800 p-12 text-center rounded-xl border border-gray-200 dark:border-slate-700 text-gray-500 text-xs">
          No security alerts match the selected criteria.
        </div>
      ) : (
        <div className="space-y-3" data-testid="alerts-feed">
          {alerts.map((alert, index) => (
            <div
              key={alert._id}
              data-testid={`alert-card-${index}`}
              className="bg-white dark:bg-slate-800 p-5 rounded-xl border border-gray-200 dark:border-slate-700 shadow-sm flex flex-col md:flex-row md:items-center justify-between gap-4"
            >
              <div className="space-y-1.5">
                <div className="flex items-center space-x-3">
                  <SeverityBadge severity={alert.severity} />
                  <StatusBadge status={alert.status} />
                  <span className="text-xs font-mono text-gray-400">
                    {new Date(alert.createdAt).toLocaleString()}
                  </span>
                </div>

                <h4 className="text-sm font-bold text-gray-900 dark:text-white pt-1">{alert.reason}</h4>

                <div className="flex flex-wrap items-center gap-4 text-xs text-gray-500 dark:text-gray-400 pt-1">
                  <span>
                    IP: <strong className="font-mono text-gray-700 dark:text-gray-200">{alert.sourceIp}</strong>
                  </span>
                  <span>
                    User: <strong className="text-gray-700 dark:text-gray-200">{alert.username}</strong>
                  </span>
                  <span>
                    Score:{' '}
                    <strong className="text-red-500 font-bold">
                      {(alert.anomalyScore * 100).toFixed(1)}%
                    </strong>
                  </span>
                  {alert.resolvedBy && (
                    <span className="text-green-600 dark:text-green-400">
                      Resolved by: {alert.resolvedBy.name || alert.resolvedBy.email}
                    </span>
                  )}
                </div>
              </div>

              {/* Triage Action Buttons */}
              <div className="flex items-center space-x-2 flex-shrink-0">
                {alert.status === 'open' && (
                  <button
                    onClick={() => handleUpdateStatus(alert._id, 'acknowledged')}
                    data-testid={`alert-action-acknowledge-${index}`}
                    className="px-3 py-1.5 rounded-lg border border-yellow-500/50 text-yellow-600 dark:text-yellow-400 hover:bg-yellow-50 dark:hover:bg-yellow-950/40 text-xs font-semibold transition"
                  >
                    Acknowledge
                  </button>
                )}

                {alert.status !== 'resolved' && (
                  <button
                    onClick={() => handleUpdateStatus(alert._id, 'resolved')}
                    data-testid={`alert-action-resolve-${index}`}
                    className="px-3 py-1.5 rounded-lg bg-green-600 hover:bg-green-700 text-white text-xs font-semibold transition flex items-center space-x-1"
                  >
                    <Check className="w-3.5 h-3.5" />
                    <span>Resolve</span>
                  </button>
                )}

                {alert.status === 'resolved' && (
                  <button
                    onClick={() => handleUpdateStatus(alert._id, 'open')}
                    data-testid={`alert-action-reopen-${index}`}
                    className="px-3 py-1.5 rounded-lg border border-gray-300 dark:border-slate-600 text-gray-500 hover:bg-gray-100 dark:hover:bg-slate-700 text-xs font-medium"
                  >
                    Reopen
                  </button>
                )}
              </div>
            </div>
          ))}

          {/* Pagination */}
          <div className="p-4 bg-white dark:bg-slate-800 rounded-xl border border-gray-200 dark:border-slate-700 flex items-center justify-between text-xs">
            <span className="text-gray-500">
              Page {pagination.page} of {pagination.totalPages} ({pagination.total} total alerts)
            </span>
            <div className="flex space-x-2">
              <button
                onClick={() => setPage((p) => Math.max(1, p - 1))}
                disabled={pagination.page <= 1}
                data-testid="alerts-pagination-prev"
                className="p-1.5 rounded-lg border border-gray-300 dark:border-slate-600 disabled:opacity-30 hover:bg-gray-50"
              >
                <ChevronLeft className="w-4 h-4" />
              </button>
              <button
                onClick={() => setPage((p) => p + 1)}
                disabled={pagination.page >= pagination.totalPages}
                data-testid="alerts-pagination-next"
                className="p-1.5 rounded-lg border border-gray-300 dark:border-slate-600 disabled:opacity-30 hover:bg-gray-50"
              >
                <ChevronRight className="w-4 h-4" />
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
